"""Write frames.txt from a Python shot list (used by episodes/<slug>/script_source.py).

    from studio.pipeline.scriptgen import Script
    s = Script(__file__, "Title")
    s.shot("B", "close", "h", "-", "RU summary", "Narration.", "Scene.", SFX="clock_tick @0 -8dB")
    s.write()

Timecodes are estimated from word counts (WPS words per second; the narration later re-times every shot
exactly); `storyboard_end` in episode.yaml is kept in sync. Every 5th shot without ANIM gets DEFAULT_ANIM.
"""

from __future__ import annotations

import re
from pathlib import Path

DEFAULT_ANIM = ("subtle natural motion, light and small details move gently || gentle camera drift || "
                "main subjects and buildings stay still")
ORDER = ("CHAPTER", "TITLE", "GFX", "FX", "CAMERA", "AMB", "SFX", "MUSIC", "AI_CLIP")


class Script:
    def __init__(self, source_file: str, title: str, wps: float = 2.55, min_s: int = 2) -> None:
        self.dir = Path(source_file).resolve().parent
        self.title, self.wps, self.min_s = title, wps, min_s
        self.shots: list[tuple] = []

    def shot(self, mode: str, kind: str, era: str, title: str, ru: str, vo: str, scene: str,
             chars: str = "-", **extra: str) -> None:
        self.shots.append((mode, kind, era, title, ru, vo, scene, chars, extra))

    def words(self) -> int:
        return sum(len(s[5].split()) for s in self.shots)

    def write(self) -> None:
        out = [f"# {self.title} — generated by script_source.py (edit there, not here).",
               "# Header: #n | m:ss | mode | shot | characters | era | title. Syntax: studio/pipeline/frames.py.", ""]
        t = 0.0
        for i, (mode, kind, era, title, ru, vo, scene, chars, extra) in enumerate(self.shots, 1):
            sec = int(round(t))
            out.append(f"#{i} | {sec // 60}:{sec % 60:02d} | {mode} | {kind} | {chars} | {era} | {title}")
            out += [f"RU: {ru}", f"VO: {vo}", f"SCENE: {scene}"]
            anim = extra.get("ANIM") or (DEFAULT_ANIM if i % 5 == 0 else "")
            if anim:
                out.append(f"ANIM: {anim}")
            for k in ORDER:
                if k in extra:
                    out.append(f"{k}: {extra[k]}")
            out.append("")
            t += max(self.min_s, round(len(vo.split()) / self.wps + 0.4))
        end = int(round(t))
        (self.dir / "frames.txt").write_text("\n".join(out), encoding="utf-8")
        cfg = self.dir / "episode.yaml"
        cfg.write_text(re.sub(r"^storyboard_end: .*$", f'storyboard_end: "{end // 60}:{end % 60:02d}"',
                              cfg.read_text(encoding="utf-8"), flags=re.M), encoding="utf-8")
        print(f"shots={len(self.shots)} words={self.words()} est={end // 60}:{end % 60:02d} storyboard_end")
