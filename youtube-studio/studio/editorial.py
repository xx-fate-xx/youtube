"""Script generation and editorial validation."""

from __future__ import annotations

import re
from dataclasses import dataclass

from studio.channels import ChannelProfile
from studio.episodes import Workspace
from studio.fsutil import atomic_write_json, atomic_write_text, read_model
from studio.models import ResearchPack, Script, VerificationStatus

MIN_WORDS, MAX_WORDS = 1200, 2200
NUMBER_PATTERN = re.compile(
    r"\d|\b(hundred|thousand|million|billion|percent|half|twice|dozen|fifty|sixty|seventy|"
    r"eighty|ninety|forty|thirty|twenty)\b",
    re.IGNORECASE,
)
QUOTE_PATTERN = re.compile(r"[\"“”]")


@dataclass(frozen=True)
class Issue:
    severity: str  # blocker | warning
    message: str

    def __str__(self) -> str:
        return f"[{self.severity}] {self.message}"


def load_script(ws: Workspace) -> Script:
    if not ws.script_file.exists():
        raise FileNotFoundError("No script yet. Run `studio script <episode>` first.")
    return read_model(ws.script_file, Script)


def save_script(ws: Workspace, script: Script, pack: ResearchPack) -> None:
    atomic_write_json(ws.script_file, script)
    atomic_write_text(ws.script / "script.md", script_markdown(script, pack))


def script_issues(script: Script, pack: ResearchPack, channel: ChannelProfile,
                  target_minutes: float) -> list[Issue]:
    issues: list[Issue] = []
    if script.is_placeholder:
        issues.append(Issue("blocker", "script is a placeholder from the mock provider"))
    wc = script.word_count
    if not MIN_WORDS <= wc <= MAX_WORDS:
        issues.append(Issue("blocker", f"word count {wc} outside {MIN_WORDS}-{MAX_WORDS}"))
    expected = target_minutes * channel.narration.words_per_minute
    if abs(wc - expected) / expected > 0.25:
        issues.append(Issue("warning", f"word count {wc} is far from target "
                                       f"~{expected:.0f} for {target_minutes:g} min"))
    claims = {c.id: c for c in pack.claims}
    for section in script.sections:
        for i, para in enumerate(section.paragraphs, start=1):
            where = f"{section.id}#{i}"
            for cid in para.claim_ids:
                if cid not in claims:
                    issues.append(Issue("blocker", f"{where} cites unknown claim {cid}"))
                elif claims[cid].status == VerificationStatus.REJECTED:
                    issues.append(Issue("blocker", f"{where} relies on rejected claim {cid}"))
            if NUMBER_PATTERN.search(para.text) and not para.claim_ids:
                issues.append(Issue("blocker", f"{where} contains a number/date but cites no "
                                               "claim"))
            if QUOTE_PATTERN.search(para.text):
                issues.append(Issue("warning", f"{where} contains quotation marks - confirm "
                                               "any quote is sourced verbatim"))
            if "[PLACEHOLDER" in para.text:
                issues.append(Issue("blocker", f"{where} is placeholder text"))
    return issues


def script_markdown(script: Script, pack: ResearchPack) -> str:
    status = {c.id: c.status.value for c in pack.claims}
    lines = [f"# {script.title}", "", f"_Words: {script.word_count} - generated by "
             f"`{script.generated_by}`_", ""]
    if script.is_placeholder:
        lines += ["> **PLACEHOLDER SCRIPT - NOT PUBLISHABLE**", ""]
    for section in script.sections:
        lines += [f"## {section.heading}", ""]
        for para in section.paragraphs:
            refs = " ".join(f"[{c}:{status.get(c, 'unknown')}]" for c in para.claim_ids)
            lines.append(f"{para.text} {refs}".rstrip())
            lines.append(f"<!-- visual: {para.visual.kind}:{para.visual.ref} -->")
            lines.append("")
    if script.editorial_notes:
        lines += ["## Editorial notes", ""] + [f"- {n}" for n in script.editorial_notes]
    return "\n".join(lines) + "\n"
