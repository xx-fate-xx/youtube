"""Visual sequences for the super-speed pilot (What If engine, studio/whatif/scene.py).

Shot numbers refer to frames.txt (generated by script_source.py from the approved script.md).
Backgrounds: projects/whatif_super_speed/bg/<id>.png. Chalk numbers repeat only fact-checked values
(factcheck_report.md).
"""

from studio.whatif.scene import Seq, arc, arrow, note, speed_value, underline


def build(size):
    seqs = []

    # 1-4  Cold open: you walk out onto the street; title; first freeze introduces the device.
    s = Seq(shots=(1, 4), bg="city", ground=975, push=(1.0, 1.05))
    hero = s.actor(x=140, h=250, hero=True)
    hero.walk(0.0)
    hero.play("stand", at=3.6, blend=0.5)
    s.actor(x=1500, h=215, ground=955, flip=True, hat="backpack").walk_b(0.0, phase=4)
    s.actor(x=1150, h=200, ground=945).walk(0.0, phase=12)
    s.title(["What if you had", "super speed?"], 0.4, s.at(2, 1.5))
    s.cut(s.at(1, 3.2), 1.6, x=0.42, y=0.58)          # medium: you
    s.cut(s.at(2), 2.3, x=0.5, y=0.52)               # close: "your body is unbreakable"
    s.cut(s.at(3), 1.0)                              # wide street
    s.cut(s.at(3, 3.5), 1.45, x=0.36, y=0.62)        # "physics still has rules"
    s.cut(s.at(4), 1.0)                              # wide for the first freeze
    s.freeze(s.at(4, 2.4), s.end(-0.2), [
        arrow(330, -170, 60, -40, t=0.2),
        note(345, -185, "YOU", 52, t=0.6, d=0.3, weight=800, family="Inter Display", anchor="hero"),
        note(345, -135, "unbreakable", 40, t=0.9, d=0.6, anchor="hero"),
    ])
    seqs.append(s)

    # 5-8  Level 1: 44 km/h. Camera runs with you. Freeze: the foot pushes with several times body weight.
    s = Seq(shots=(5, 8), bg="city", ground=975, push=(1.0, 1.03))
    hero = s.actor(x=620, h=250, hero=True)
    hero.play("stand", at=0.0)
    hero.run(s.at(5, 0.6), cadence=s.ramp([(s.at(5, 0.6), 0.9), (s.at(5, 2.6), 1.45)]))
    s.follow(hero, s.at(5, 0.6))
    for x, hh, g, flip, ph in ((1500, 225, 955, True, 0), (2400, 210, 948, False, 9), (3600, 230, 962, True, 5),
                               (5200, 220, 952, False, 14), (7000, 215, 950, True, 3)):
        s.actor(x=x, h=hh, ground=g, flip=flip).walk(0.0, phase=ph)
    kmh = s.ramp([(s.at(5, 0.6), 5), (s.at(5, 2.6), 44)])
    s.hud("LEVEL 1", speed_value(kmh), "Usain Bolt's top speed", s.at(5, 0.2), s.end(), note_at=s.at(5, 2.6))
    s.cut(0.0, 1.5, x=0.45, y=0.6)                   # medium: about to run
    s.cut(s.at(5, 0.9), 1.0)                         # wide: off he goes
    s.cut(s.at(6), 1.85, x=0.42, y=0.55)             # close tracking: wind in your face
    s.cut(s.at(6, 3.4), 1.0)
    s.cut(s.at(7), 1.4, x=0.36, y=0.66)              # low medium: studies of runners
    s.cut(s.at(8), 1.0)                              # wide for the freeze
    s.freeze(s.at(8, 0.2), s.end(-0.3), [
        arrow(170, 40, 25, 150, t=0.2),
        note(185, 35, "several × body weight", 42, t=0.6, anchor="hero"),
        note(185, 85, "every step, for a split second", 34, t=1.3, weight=500, anchor="hero"),
    ])
    seqs.append(s)

    # 9-16 Level 2: 130 km/h. Freeze 1: reaction distance. Freeze 2: the tightest curve.
    s = Seq(shots=(9, 16), bg="meadow", ground=985, push=(1.0, 1.03), depth=0.79)
    hero = s.actor(x=760, h=260, hero=True)
    hero.run(0.0, cadence=s.ramp([(0.0, 1.45), (s.at(9, 2.0), 2.4)]))
    s.follow(hero, 0.0)
    for x, hh, g, flip, ph in ((2600, 190, 905, True, 2), (6800, 180, 900, False, 7), (11000, 200, 915, True, 11)):
        s.actor(x=x, h=hh, ground=g, flip=flip).walk(0.0, phase=ph)
    kmh = s.ramp([(0.0, 44), (s.at(9, 2.0), 130)])
    s.hud("LEVEL 2", speed_value(kmh), "motorway speed", 0.2, s.end(), note_at=s.at(9, 2.0))
    s.speed_lines(s.at(9, 1.0), s.end())
    s.cut(s.at(9, 2.6), 1.5, x=0.4, y=0.6)
    s.cut(s.at(10), 2.0, x=0.45, y=0.5)              # close: "the real trouble is your brain"
    s.cut(s.at(11), 1.0)                             # wide for the reaction-distance freeze
    s.cut(s.at(13), 1.4, x=0.35, y=0.62)             # grip
    s.cut(s.at(14), 1.9, x=0.42, y=0.75)             # close on the feet
    s.cut(s.at(15), 1.0)                             # wide for the curve
    s.freeze(s.at(12, 0.2), s.at(13), [
        underline(900, 900, 1700, t=0.2, d=0.5),
        note(900, 870, "0.25 – 1 s to react", 42, t=0.6),
        note(1450, 965, "9 – 36 m", 64, t=1.2, d=0.4, weight=800, family="Inter Display"),
    ])
    s.freeze(s.at(15, 0.2), s.end(-0.3), [
        arc(60, 40, 900, -330, 160, t=0.2, d=0.9),
        note(420, -420, "tightest curve:", 40, t=1.0, anchor="hero"),
        note(420, -355, "r ≈ 170 m", 64, t=1.4, d=0.4, weight=800, family="Inter Display", anchor="hero"),
    ])
    seqs.append(s)
    return seqs
